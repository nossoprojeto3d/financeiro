// Contas a pagar no iPhone: cartão do Início, tela A pagar, anotar, Paguei e as que voltam todo mês.
import { test, expect, digitarValor, escolherCategoria, aviso, semEspacos } from './base.js'

const lancamento = page => page.getByRole('dialog', { name: 'Lançamento' })
const conta = (page, nome) => page.getByRole('list', { name: 'Contas a pagar' }).getByRole('listitem').filter({ hasText: nome })
const banco = page => page.evaluate(() => window.__bancoFalso.db())
async function abrirAPagar(page) {
  await page.getByRole('button', { name: /^A pagar/ }).click()
  await expect(page.getByRole('heading', { name: 'A pagar' })).toBeVisible()
}

test('o cartão do Início mostra o total e a atrasada, e a lista vem pela ordem do vencimento', async ({ page }) => {
  const cartao = page.getByRole('button', { name: /^A pagar/ })
  expect(await semEspacos(cartao)).toContain('R$1.049,90')
  await expect(cartao.getByText('1 atrasada')).toHaveClass(/text-sai/)
  await abrirAPagar(page)
  const nomes = await page.getByRole('list', { name: 'Contas a pagar' }).getByRole('listitem').allInnerTexts()
  expect(nomes.map(t => t.split('\n')[0])).toEqual(['Boleto filamento', 'Internet', 'Energia', 'Parcela da impressora'])
  await expect(conta(page, 'Boleto filamento')).toContainText('atrasada há 2 dias')
  await expect(conta(page, 'Internet')).toContainText('vence hoje')
  await expect(conta(page, 'Energia')).toContainText('vence em 3 dias')
  await expect(conta(page, 'Energia').getByLabel('Todo mês')).toBeVisible()
})

test('anotar uma conta que volta todo mês pela tela A pagar', async ({ page }) => {
  await abrirAPagar(page)
  await page.getByRole('main').getByRole('button', { name: 'Anotar conta' }).click()
  const l = lancamento(page)
  await expect(l.getByText('Nova conta a pagar')).toBeVisible()
  await digitarValor(l, '1200')
  await escolherCategoria(l, page, 'Energia e internet')
  await l.getByPlaceholder(/^Que conta é/).fill('Aluguel')
  await l.getByRole('button', { name: /Vence/ }).click()
  const det = page.getByRole('dialog', { name: 'Detalhes' })
  await expect(det.getByText('Vence em')).toBeVisible()
  await expect(det.getByText('Forma de pagamento')).toBeHidden()
  const daqui10 = await page.evaluate(() => { const d = new Date(); d.setDate(d.getDate() + 10); return `${d.getFullYear()}-${String(d.getMonth() + 1).padStart(2, '0')}-${String(d.getDate()).padStart(2, '0')}` })
  await det.getByLabel('Dia do vencimento').fill(daqui10)
  await det.getByRole('button', { name: /Repetir todo mês/ }).click()
  await expect(det.getByText(/A conta volta todo dia \d+, esperando o Paguei/)).toBeVisible()
  await det.getByRole('button', { name: 'Pronto' }).click()
  await l.getByRole('button', { name: 'Anotar conta' }).click()
  await aviso(page, 'Conta mensal anotada')
  // mais de 7 dias: mostra o dia
  await expect(conta(page, 'Aluguel')).toContainText(`vence ${daqui10.slice(8)}/${daqui10.slice(5, 7)}`)
  await expect(conta(page, 'Aluguel').getByLabel('Todo mês')).toBeVisible()
  const db = await banco(page)
  expect(db.contas_regras.filter(r => r.descricao === 'Aluguel')).toHaveLength(1)
  expect((await banco(page)).lancamentos.filter(x => x.descricao?.startsWith('Aluguel'))).toHaveLength(0) // não saiu do caixa
})

test('anotar conta pela saída comum (Detalhes › Ainda não paguei)', async ({ page }) => {
  await page.getByRole('navigation').getByRole('button', { name: 'Novo lançamento' }).click()
  const l = lancamento(page)
  await l.getByRole('radio', { name: 'Saída' }).click()
  await l.getByRole('button', { name: /Detalhes/ }).click()
  const det = page.getByRole('dialog', { name: 'Detalhes' })
  await det.getByRole('button', { name: /Ainda não paguei/ }).click()
  await expect(det.getByText('Vence em')).toBeVisible()
  await expect(det.getByText('Forma de pagamento')).toBeHidden()
  await det.getByRole('button', { name: 'Pronto' }).click()
  await expect(l.getByText('Nova conta a pagar')).toBeVisible()
  await expect(l.getByRole('button', { name: 'Anotar conta' })).toBeVisible()
})

test('Paguei com outro valor: vira saída, sai da lista e a mensal avisa que volta', async ({ page }) => {
  await abrirAPagar(page)
  await conta(page, 'Energia').getByRole('button', { name: 'Paguei' }).click()
  const p = page.getByRole('dialog', { name: 'Paguei: Energia' })
  await p.getByRole('button', { name: 'Confirmar R$ 180,00' }).click()
  await aviso(page, 'Escolha a forma de pagamento.')
  await p.getByRole('button', { name: 'Outro valor' }).click()
  await digitarValor(p, '195,40')
  await p.getByRole('button', { name: 'Pix' }).click()
  await p.getByRole('button', { name: 'Confirmar R$ 195,40' }).click()
  await aviso(page, 'Paga · a do mês que vem aparece sozinha')
  await expect(conta(page, 'Energia')).toHaveCount(0)
  const saida = (await banco(page)).lancamentos.find(x => x.descricao?.startsWith('Energia · vencimento'))
  expect(saida).toMatchObject({ tipo: 'saida', valor: 195.4, forma_pagamento: 'Pix' })
})

test('se o outro celular mexer na conta antes, o Paguei é recusado e a lista atualiza', async ({ page }) => {
  await abrirAPagar(page)
  await conta(page, 'Internet').getByRole('button', { name: 'Paguei' }).click()
  const p = page.getByRole('dialog', { name: 'Paguei: Internet' })
  await p.getByRole('button', { name: 'Dinheiro' }).click()
  await page.evaluate(() => { const b = window.__bancoFalso, c = b.db().contas.find(x => x.id === 2); c.valor = 120; c.atualizado_em = 'outro'; b.salvar() })
  await p.getByRole('button', { name: 'Confirmar R$ 99,90' }).click()
  await aviso(page, 'Essa conta mudou agora há pouco (outro celular). Confira a lista e tente de novo.')
  await expect(p).toBeHidden()
  await expect(conta(page, 'Internet')).toContainText('120,00')
  expect((await banco(page)).lancamentos.filter(x => x.descricao?.startsWith('Internet ·'))).toHaveLength(0)
})

test('editar a conta mensal e desligar o Repetir para de gerar as próximas', async ({ page }) => {
  await abrirAPagar(page)
  await conta(page, 'Energia').getByRole('button', { name: /^Energia/ }).click()
  const l = lancamento(page)
  await expect(l.getByText('Editando conta a pagar')).toBeVisible()
  await l.getByRole('button', { name: /Vence/ }).click()
  await page.getByRole('dialog', { name: 'Detalhes' }).getByRole('button', { name: /Repetir todo mês/ }).click()
  await page.getByRole('dialog', { name: 'Detalhes' }).getByRole('button', { name: 'Pronto' }).click()
  await l.getByRole('button', { name: 'Salvar alterações' }).click()
  await aviso(page, 'Alterações salvas')
  await expect(conta(page, 'Energia').getByLabel('Todo mês')).toHaveCount(0)
  expect((await banco(page)).contas_regras).toHaveLength(0)
})

test('excluir uma conta', async ({ page }) => {
  await abrirAPagar(page)
  await conta(page, 'Parcela da impressora').getByRole('button', { name: /^Parcela/ }).click()
  await lancamento(page).getByRole('button', { name: 'Excluir conta' }).click()
  const conf = page.getByRole('dialog', { name: 'Excluir conta?' })
  await expect(conf).toContainText('A conta Parcela da impressora (R$ 450,00) sai da lista.')
  await conf.getByRole('button', { name: 'Excluir' }).click()
  await aviso(page, 'Conta excluída')
  await expect(conta(page, 'Parcela da impressora')).toHaveCount(0)
})

