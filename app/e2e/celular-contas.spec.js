test('com o banco ainda sem o SQL das contas, o app abre normal, só sem o A pagar', async ({ page }) => {
  await page.evaluate(() => { const b = window.__bancoFalso, db = b.db(); delete db.contas; delete db.contas_regras; b.salvar(); localStorage.removeItem('caixa_cache') })
  await page.reload()
  await expect(page.getByText('Em caixa')).toBeVisible()
  await expect(page.getByRole('button', { name: /^A receber/ })).toBeVisible()
  await expect(page.getByRole('button', { name: /^A pagar/ })).toHaveCount(0)
  // e a saída comum não oferece o "Ainda não paguei"
  await page.getByRole('navigation').getByRole('button', { name: 'Novo lançamento' }).click()
  await page.getByRole('dialog', { name: 'Lançamento' }).getByRole('radio', { name: 'Saída' }).click()
  await page.getByRole('dialog', { name: 'Lançamento' }).getByRole('button', { name: /Detalhes/ }).click()
  await expect(page.getByRole('dialog', { name: 'Detalhes' }).getByText('Ainda não paguei')).toHaveCount(0)
})
